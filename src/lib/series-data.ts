export function getSeriesRoundUnlockTime(dayNumber: number, startIso: string = SERIES_64_START_ISO): string {
  const startDate = new Date(startIso)
  const unlockDate = new Date(startDate.getTime() + (dayNumber - 1) * 24 * 60 * 60 * 1000)
  return unlockDate.toISOString()
}

export function isRoundEffectivelyUnlocked(round: {
  is_unlocked?: boolean
  unlock_at?: string
  activePin?: string | null
}): boolean {
  if (round.activePin) return true
  if (round.unlock_at) {
    return new Date() >= new Date(round.unlock_at)
  }
  return Boolean(round.is_unlocked)
}

